const DICTIONARIES: Record<LangCode, Partial<Record<Key, string>>> = { en: EN, nl: NL, fr: FR };
const STORAGE_KEY = "vibin_lang";
const INTL_LOCALE: Record<LangCode, string> = { en: "en-GB", nl: "nl-BE", fr: "fr-BE" };

type Vars = Record<string, string | number>;
const interpolate = (s: string, vars?: Vars) =>
  vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;

/** Display label for a shared-constant id (category, budget band, ...) — falls back to the given default when no translation key exists, so admin-added categories still render. */
export function labelFor(
  t: (k: Key) => string,
  prefix: "cat" | "budget" | "dateMode" | "timeBand",
  id: string,
  fallback: string,
): string {
  const k = `${prefix}.${id}`;
  return k in EN ? t(k as Key) : fallback;
}

/** Non-hook access for plain helpers (date/time formatting) that render outside React's tree. */
let activeLang: LangCode = "en";
export const intlLocale = () => INTL_LOCALE[activeLang];
export const translate = (k: Key, vars?: Vars) =>
  interpolate(DICTIONARIES[activeLang]?.[k] ?? EN[k], vars);

const Ctx = createContext<{ lang: LangCode; setLang: (l: LangCode) => void; t: (k: Key, vars?: Vars) => string }>({
  lang: "en",
  setLang: () => {},
  t: (k, vars) => interpolate(EN[k], vars),
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved && LANGUAGES.some((l) => l.code === saved)) {
        activeLang = saved as LangCode;
        return saved as LangCode;
      }
    } catch {
      /* private mode / blocked storage — English default is fine */
    }
    return "en";
  });

  const setLang = (l: LangCode) => {
    activeLang = l;
    setLangState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* per-viewer convenience only — nothing depends on this persisting */
    }
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo(
    () => ({
      lang,
      setLang,
      // English is the always-complete base; other languages only override
      // the keys they actually have — this IS the fallback, not a bug path.
      t: (k: Key, vars?: Vars) => interpolate(DICTIONARIES[lang]?.[k] ?? EN[k], vars),
    }),
    [lang],
  );

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useLang() {
  return useContext(Ctx);
}
